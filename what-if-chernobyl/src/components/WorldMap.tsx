/**
 * Dotted world map. `children` are drawn on top in map coordinates
 * (use `project(lon, lat)` from lib/geo to place markers).
 */
export const WorldMap: React.FC<{width?: number; color?: string; children?: React.ReactNode}> = ({
  width = 1000,
  color = '#2e5a8a',
  children,
}) => (
  <svg width={width} height={(width * 400) / MAP_W} viewBox="0 20 1000 400" style={{overflow: 'visible'}}>
    <defs>
      <pattern id="map-dots" width={9} height={9} patternUnits="userSpaceOnUse">
        <circle cx={4.5} cy={4.5} r={3.2} fill={color} />
      </pattern>
    </defs>
    {CONTINENTS.map((pts, i) => (
      <path
        key={i}
        d={'M' + pts.map(([lon, lat]) => project(lon, lat).map((v) => v.toFixed(1)).join(' ')).join(' L') + ' Z'}
        fill="url(#map-dots)"
      />
    ))}
    {children}
  </svg>
);
